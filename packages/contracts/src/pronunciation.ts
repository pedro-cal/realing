import { z } from 'zod';

export const PhonemeStatusSchema = z.enum(['correct', 'imprecise', 'incorrect']);
export type PhonemeStatus = z.infer<typeof PhonemeStatusSchema>;

export const PhonemeAssessmentSchema = z.object({
  phoneme: z.string(), // IPA character
  score: z.number().min(0).max(100),
  status: PhonemeStatusSchema,
});

export type PhonemeAssessment = z.infer<typeof PhonemeAssessmentSchema>;

export const WordAssessmentSchema = z.object({
  word: z.string(),
  startTimeMs: z.number().nonnegative(),
  endTimeMs: z.number().nonnegative(),
  score: z.number().min(0).max(100),
  phonemes: z.array(PhonemeAssessmentSchema),
});

export type WordAssessment = z.infer<typeof WordAssessmentSchema>;

export const PronunciationReportSchema = z.object({
  submissionId: z.string().uuid(),
  audioId: z.string().uuid(),
  targetText: z.string(),
  recognizedText: z.string(),
  overallScore: z.number().min(0).max(100),
  accuracyScore: z.number().min(0).max(100),
  fluencyScore: z.number().min(0).max(100),
  completenessScore: z.number().min(0).max(100),
  words: z.array(WordAssessmentSchema),
  pedagogicalFeedback: z.string(), // Actionable pronunciation tip generated by AI
  evaluatedAt: z.string().datetime(),
});

export type PronunciationReport = z.infer<typeof PronunciationReportSchema>;
